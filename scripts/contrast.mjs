#!/usr/bin/env node
// WCAG 2.1 contrast for the text/background pairs the primitives actually use.
// Reads hex tokens from frontend/src/index.css and writes docs/CONTRAST.md.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const css = readFileSync(join(ROOT, 'frontend', 'src', 'index.css'), 'utf8');

const tokens = new Map();
for (const match of css.matchAll(/--([a-z0-9-]+):\s*(#[0-9a-fA-F]{6})\s*;/g)) {
  tokens.set(match[1], match[2].toLowerCase());
}

function channel(hex, index) {
  const value = parseInt(hex.slice(1 + index * 2, 3 + index * 2), 16) / 255;
  return value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4;
}

function luminance(hex) {
  const r = channel(hex, 0);
  const g = channel(hex, 1);
  const b = channel(hex, 2);
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

function ratio(fg, bg) {
  const lighter = Math.max(luminance(fg), luminance(bg));
  const darker = Math.min(luminance(fg), luminance(bg));
  return (lighter + 0.05) / (darker + 0.05);
}

const pairs = [
  ['ink on bg', 'ink', 'bg', 'normal', 'body text'],
  ['muted on bg', 'muted', 'bg', 'normal', 'secondary text'],
  ['dim on bg', 'dim', 'bg', 'normal', 'kickers and captions'],
  ['acid-green on bg', 'acid-green', 'bg', 'large', 'display type, cursor, loader'],
  ['acid-pink on bg', 'acid-pink', 'bg', 'normal', 'outline hover, error toast'],
  ['paper-ink on powder-grey', 'paper-ink', 'powder-grey', 'normal', 'paper cards'],
  ['paper-ink on warm-ash', 'paper-ink', 'warm-ash', 'normal', 'alternate paper'],
  ['paper-ink on smoke-grey', 'paper-ink', 'smoke-grey', 'normal', 'available paper tone'],
  ['paper-ink on acid-green', 'paper-ink', 'acid-green', 'normal', 'primary button, green tile, badge'],
  ['paper-ink on acid-pink', 'paper-ink', 'acid-pink', 'normal', 'primary hover, pink badge'],
  ['powder-grey on paper-ink', 'powder-grey', 'paper-ink', 'normal', 'light window chrome'],
  ['paper-ink on power-blue', 'paper-ink', 'power-blue', 'normal', 'ecstasy chip'],
  ['paper-ink on power-pink', 'paper-ink', 'power-pink', 'normal', 'ecstasy chip'],
  ['paper-ink on soft-blue', 'paper-ink', 'soft-blue', 'normal', 'ecstasy chip'],
  ['paper-ink on muted-pink', 'paper-ink', 'muted-pink', 'normal', 'ecstasy chip'],
  ['paper-ink on soft-orange', 'paper-ink', 'soft-orange', 'normal', 'ecstasy chip'],
  ['paper-ink on banana', 'paper-ink', 'banana', 'normal', 'ecstasy chip'],
];

const lines = [
  '# Contrast',
  '',
  'Generated by `node scripts/contrast.mjs`. Pairs are the ones the UI primitives use.',
  'AA normal requires 4.5:1. AA large (18px regular or 14px bold) requires 3:1.',
  'Acid green text is limited to large display type. It is never placed on paper.',
  '',
  '| Pair | Ratio | AA normal | AA large | Use |',
  '|---|---:|---|---|---|',
];

let failed = false;
for (const [name, fgName, bgName, size, use] of pairs) {
  const fg = tokens.get(fgName);
  const bg = tokens.get(bgName);
  if (!fg || !bg) {
    console.error(`Missing token for ${name}`);
    failed = true;
    continue;
  }
  const value = ratio(fg, bg);
  const normal = value >= 4.5;
  const large = value >= 3;
  const pass = size === 'large' ? large : normal;
  if (!pass) failed = true;
  lines.push(`| ${name} | ${value.toFixed(2)} | ${normal ? 'pass' : 'fail'} | ${large ? 'pass' : 'fail'} | ${use} |`);
}

lines.push('');
writeFileSync(join(ROOT, 'docs', 'CONTRAST.md'), `${lines.join('\n')}\n`);
console.log(lines.join('\n'));
if (failed) {
  console.error('\nA used pair fails AA.');
  process.exit(1);
}
console.log('\nAll used pairs pass.');
